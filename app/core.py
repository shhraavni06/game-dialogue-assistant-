def preprocess_dialogues(dialogues=None):
    source = GAME_DIALOGUES if dialogues is None else dialogues
    cleaned = []
    for line in source:
        line = re.sub(r"[^a-zA-Z0-9' ]", " ", line.lower())
        tokens = re.findall(r"[a-z0-9']+", line)
        if tokens:
            cleaned.append(tokens)
    return cleaned
